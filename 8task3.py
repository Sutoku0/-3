# Запрашиваем у пользователя ввод числа n с подсказкой
n = int(input('Введите положительное целое число n: '))

# Вычисляем количество чисел от 1 до n, которые не делятся на 2, 3 и 5
result = sum(
    (num % 2 != 0) and (num % 3 != 0) and (num % 5 != 0)
    for num in range(1, n + 1)
)

# Выводим результат
print(result)