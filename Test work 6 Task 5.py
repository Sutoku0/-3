# Ввод координат
col1 = int(input("Введите номер столбца первой клетки (от 1 до 8): "))
row1 = int(input("Введите номер строки первой клетки (от 1 до 8): "))
col2 = int(input("Введите номер столбца второй клетки (от 1 до 8): "))
row2 = int(input("Введите номер строки второй клетки (от 1 до 8): "))

# Проверка допустимости номеров
if max(col1, row1, col2, row2) > 8:
    print("Ошибка: номера не должны быть больше 8.")
else:
    # Проверка возможности хода ферзя без abs
    if (col1 == col2) or (row1 == row2) or ((col2 - col1) == (row2 - row1)) or ((col2 - col1) == (row1 - row2)):
        print("YES")
    else:
        print("NO")